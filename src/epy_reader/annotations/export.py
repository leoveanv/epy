"""One-way Markdown export. Never replace content outside this book's delimiters."""

import hashlib
import html
import os
import shutil
import stat
import sys
import tempfile
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, List, Optional, Sequence, cast

from epy_reader.annotations.models import Annotation, AnnotationBook, stable_location
from epy_reader.annotations.store import AnnotationStore


class ExportConflict(ValueError):
    pass


@dataclass(frozen=True)
class MergedSection:
    content: bytes
    digest: str


def validate_destination(value: str) -> Path:
    if not value or "\x00" in value or "\n" in value or "\r" in value:
        raise ValueError("Paste a single literal absolute Markdown file path.")
    path = Path(value)
    if not path.is_absolute() or path.suffix.lower() != ".md":
        raise ValueError("The destination must be an absolute .md file path.")
    path = path.resolve()
    if not path.parent.is_dir() or (path.exists() and not path.is_file()):
        raise ValueError("The destination needs an existing parent directory and must be a file.")
    return path


def literal_markdown(value: str) -> str:
    escaped = html.escape(value, quote=False)
    for char in "\\`*_{}[]()#+!|":
        escaped = escaped.replace(char, "\\" + char)
    return escaped


def reference_label(annotation: Annotation) -> str:
    reference = annotation.reference
    if reference is not None and reference.page_start:
        if reference.page_end and reference.page_end != reference.page_start:
            return "Pages " + reference.page_start + "–" + reference.page_end
        return "Page " + reference.page_start
    return (
        reference.location
        if reference is not None and reference.location
        else stable_location(annotation.anchor, annotation.content_order)
    )


def heading_lines(headings: Sequence[str], previous: Sequence[str]) -> List[str]:
    common = 0
    while common < min(len(headings), len(previous)) and headings[common] == previous[common]:
        common += 1
    if len(headings) < len(previous) and common == len(headings):
        common = max(0, common - 1)
    lines = []
    for index in range(common, len(headings)):
        title = literal_markdown(headings[index].replace("\n", " "))
        lines.extend(["#" * min(6, index + 3) + " " + title, ""])
    return lines


def annotation_lines(annotation: Annotation) -> List[str]:
    lines = ["**" + literal_markdown(reference_label(annotation)) + "**", ""]
    lines.extend("> " + literal_markdown(line) for line in annotation.anchor.quote.splitlines())
    lines.extend(["", "^epy-" + annotation.id, ""])
    if annotation.note:
        lines.extend(["**Note**", "", literal_markdown(annotation.note), ""])
    return lines


def render_section(
    book: AnnotationBook, annotations: Sequence[Annotation], newline: str = "\n"
) -> bytes:
    lines = [
        "<!-- epy:annotations:" + book.id + ":start -->",
        "## Highlights from " + literal_markdown(book.title.replace("\n", " ")),
        "",
        "<!-- Generated by epy. Personal notes belong outside this section. -->",
        "",
    ]
    previous = cast(Sequence[str], ())
    for index, annotation in enumerate(annotations):
        headings = (
            tuple(annotation.reference.headings)
            if annotation.reference and annotation.reference.headings
            else (annotation.chapter or "Highlights",)
        )
        if index:
            lines.extend(["---", ""])
        lines.extend(heading_lines(headings, previous))
        lines.extend(annotation_lines(annotation))
        previous = headings
    lines.append("<!-- epy:annotations:" + book.id + ":end -->")
    return newline.join(lines).encode("utf-8")


def merge_section(
    content: bytes,
    book_id: str,
    section: bytes,
    expected_digest: Optional[str],
    overwrite: bool = False,
) -> MergedSection:
    prefix = ("<!-- epy:annotations:" + book_id + ":").encode()
    start_marker, end_marker = prefix + b"start -->", prefix + b"end -->"
    count = content.count(prefix)
    if count == 0:
        if expected_digest is not None:
            raise ExportConflict(
                "The linked epy section is missing. Relink explicitly to append a new section."
            )
        separator = b"\r\n" if b"\r\n" in content else b"\n"
        merged = content + (separator * 2 if content else b"") + section + separator
    else:
        if count != 2 or content.count(start_marker) != 1 or content.count(end_marker) != 1:
            raise ExportConflict("The epy section has duplicate or malformed delimiters.")
        start = content.index(start_marker)
        end_start = content.index(end_marker)
        end = end_start + len(end_marker)
        if end_start <= start:
            raise ExportConflict("The epy section delimiters are out of order.")
        previous = hashlib.sha256(content[start:end]).hexdigest()
        desired = hashlib.sha256(section).hexdigest()
        if not overwrite and previous != expected_digest and previous != desired:
            raise ExportConflict(
                "The epy section changed outside epy. Confirm overwrite in O to replace it."
            )
        merged = content[:start] + section + content[end:]
    return MergedSection(merged, hashlib.sha256(section).hexdigest())


@contextmanager
def destination_lock(path: Path) -> Iterator[None]:
    with path.with_name("." + path.name + ".epy.lock").open("a+b") as lock:
        if sys.platform == "win32":
            import msvcrt

            lock.write(b"0")
            lock.flush()
            lock.seek(0)
            msvcrt.locking(lock.fileno(), msvcrt.LK_LOCK, 1)
        else:
            import fcntl

            fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            if sys.platform == "win32":
                lock.seek(0)
                msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


def atomic_replace(path: Path, before: bytes, after: bytes) -> None:
    mode = stat.S_IMODE(path.stat().st_mode)
    descriptor, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "wb") as destination:
            destination.write(after)
            destination.flush()
            os.fsync(destination.fileno())
        os.chmod(temporary, mode)
        if path.read_bytes() != before:
            raise ExportConflict("The destination changed during export. Retry after saving it.")
        backup = path.with_name("." + path.name + ".epy.bak")
        shutil.copy2(path, backup)
        if path.read_bytes() != before:
            raise ExportConflict("The destination changed during export. Retry after saving it.")
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def export_book(
    store: AnnotationStore, book: AnnotationBook, overwrite: bool = False
) -> Optional[str]:
    link = store.get_link(book.id)
    if link is None:
        return None
    path = validate_destination(link.path)
    with destination_lock(path):
        link = store.get_link(book.id)
        if link is None or Path(link.path).resolve() != path:
            raise ExportConflict("The book link changed during export. Retry.")
        original = path.read_bytes()
        newline = "\r\n" if b"\r\n" in original else "\n"
        annotations = store.list_annotations(book.id)
        section = render_section(book, annotations, newline)
        merged = merge_section(original, book.id, section, link.digest, overwrite)
        if merged.content != original:
            atomic_replace(path, original, merged.content)
        store.mark_exported(link, merged.digest)
        return merged.digest
